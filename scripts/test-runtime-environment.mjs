import assert from 'node:assert/strict';
import { parseTelegramLaunch, detectTelegram, resolveTheme, themeMode, copyRetention, createRuntimeEnvironment, readBridgeTheme, themeFromParams } from '../public/runtime-environment.mjs';
import { sanitizeTelegramPalette, applyTelegramPalette, telegramNativeColors } from '../public/telegram-palette.mjs';
const origin='https://example.com/';
const make=(platform='android',bg='#101827')=>origin+'#'+new URLSearchParams({tgWebAppPlatform:platform,tgWebAppVersion:'9.0',tgWebAppThemeParams:JSON.stringify({bg_color:bg})});
assert.deepEqual(parseTelegramLaunch(make()),{platform:'android',version:'9.0',theme:'dark',colors:{bg_color:'#101827'}});
assert.equal(parseTelegramLaunch(make('ios','#FFFFFF')).theme,'light');
assert.equal(parseTelegramLaunch(origin+'#song-title'),null);
assert.equal(parseTelegramLaunch(origin+'?tgWebAppPlatform=android'),null);
assert.equal(parseTelegramLaunch(make('unknown')),null);
assert.equal(detectTelegram({url:origin,api:{platform:'android',version:'9.0',colorScheme:'dark',initData:''}}),null);
assert.equal(detectTelegram({url:origin,session:{platform:'ios',version:'9.0',theme:'dark'}}).platform,'ios');
for(const system of ['light','dark'])for(const telegram of ['light','dark',null]){
  assert.equal(resolveTheme('auto',system,telegram),telegram||system);
  for(const explicit of ['light','dark'])assert.equal(resolveTheme(explicit,system,telegram),explicit);
}
assert.equal(themeFromParams({bg_color:'#17212b'}),'dark');
assert.equal(themeFromParams({bg_color:'#ffffff'}),'light');
assert.equal(themeFromParams({bg_color:'invalid'}),null);
assert.equal(readBridgeTheme({colorScheme:'light'},'dark'), 'dark','Uninitialized SDK cannot erase launch theme');
assert.equal(readBridgeTheme({colorScheme:'dark'},'light',true),'dark','Confirmed event overrides launch theme');
assert.equal(readBridgeTheme({themeParams:{bg_color:'#ffffff'},colorScheme:'light'},'dark'),'light');
assert.equal(readBridgeTheme({themeParams:{bg_color:'#17212b'}},'light'),'dark');
assert.equal(themeMode(''),'auto');assert.equal(themeMode('bad'),'auto');
assert.equal(copyRetention('v1',false,false),'checking');
assert.equal(copyRetention(null,true,true),'unknown');
assert.equal(copyRetention('v1',true,true),'retained');
assert.equal(copyRetention('v1',true,false),'missing');
const sw={};const win={location:{href:origin},document:{},navigator:{serviceWorker:sw},matchMedia:()=>({matches:false}),sessionStorage:{getItem:()=>null},localStorage:{getItem:()=>null}};
const env=createRuntimeEnvironment(win);
assert.equal(env.isTelegram,false);assert.equal(env.serviceWorker,sw);assert.equal(env.canOfferInstall(),true);assert.equal(env.launchLabel(),'Браузер');
const p={bg_color:'#233344',text_color:'#eeeEEE',button_color:'#22AA88',bottom_bar_bg_color:'#112233',unknown:'#abcdef',hint_color:'url(bad)'};
assert.deepEqual(sanitizeTelegramPalette(p),{bg_color:'#233344',text_color:'#eeeeee',button_color:'#22aa88',bottom_bar_bg_color:'#112233'});
const props=new Map(),root={dataset:{},style:{getPropertyValue:k=>props.get(k)||'',setProperty:(k,v)=>props.set(k,v),removeProperty:k=>props.delete(k)}};
assert.equal(applyTelegramPalette(root,'auto',p),true);
assert.equal(root.dataset.telegramPalette,'active');
assert.equal(props.get('--masljanica-tg-bg-color'),'#233344');
assert.equal(props.get('--masljanica-tg-button-color'),'#22aa88');
assert.equal(applyTelegramPalette(root,'auto',{...p,bg_color:'#445566',button_color:'#ffcc00'}),true);
assert.equal(props.get('--masljanica-tg-bg-color'),'#445566');
assert.equal(props.get('--masljanica-tg-button-color'),'#ffcc00');
assert.equal(applyTelegramPalette(root,'light',p),false);
assert.equal(root.dataset.telegramPalette,undefined);
assert.equal(props.size,0);
assert.equal(applyTelegramPalette(root,'auto',{button_color:'#22aa88'}),false);
assert.deepEqual(telegramNativeColors('auto','dark',p),{background:'#233344',header:'#233344',bottom:'#112233'});
assert.deepEqual(telegramNativeColors('dark','dark',p),{background:'#101827',header:'#1D2B40',bottom:'#1D2B40'});
console.log('Runtime environment isolation, launch detection, theme priority and retention checks passed.');
