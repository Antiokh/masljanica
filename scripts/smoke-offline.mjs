import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
const origin='http://localhost:4321';
const server=spawn('npm',['run','preview','--','--host','localhost','--port','4321'],{stdio:'inherit'});
let browser;
try {
  for(let i=0;i<60;i++){
    try{if((await fetch(origin)).ok)break;}catch{}
    if(i===59)throw Error('Preview did not start');
    await new Promise(r=>setTimeout(r,500));
  }
  browser=await chromium.launch({headless:true});
  const context=await browser.newContext({viewport:{width:390,height:844}});
  let providerRequests=0;
  await context.route('https://www.youtube-nocookie.com/**',route=>{providerRequests++;return route.fulfill({contentType:'text/html',body:'<html><body>Video fixture</body></html>'});});
  const page=await context.newPage();
  await page.goto(origin);
  await page.setViewportSize({width:1440,height:900});
  const themeSwitch=page.locator('[data-theme-switch]');
  await themeSwitch.waitFor({state:'visible'});
  await themeSwitch.focus();
  await themeSwitch.press('Home');
  await page.waitForFunction(()=>document.documentElement.dataset.theme==='light' && localStorage.getItem('starlight-theme')==='light');
  await themeSwitch.press('End');
  await page.waitForFunction(()=>document.documentElement.dataset.theme==='dark' && localStorage.getItem('starlight-theme')==='dark');
  await themeSwitch.press('ArrowLeft');
  await page.waitForFunction(()=>document.querySelector('[data-theme-switch]')?.getAttribute('data-theme-mode')==='auto');
  await page.setViewportSize({width:390,height:844});
  await themeSwitch.waitFor({state:'hidden'});
  await page.locator('.mobile-theme-control').waitFor({state:'visible'});

  await page.waitForFunction(()=>!!navigator.serviceWorker.controller);
  await page.locator('#pwa-storage-accept').click();
  await page.locator('.festival-brand-icon').click();
  await page.locator('#festival-pwa-menu').waitFor({state:'visible'});
  await page.locator('[data-pwa-auto]').waitFor({state:'visible'});
  assert.equal(await page.locator('[data-pwa-auto]').getAttribute('aria-checked'),'false');
  assert.equal(await page.locator('[data-pwa-delete]').isDisabled(),true);
  const bounds=await page.locator('#festival-pwa-menu').boundingBox();
  assert.ok(bounds.x>=0&&bounds.x+bounds.width<=390,'Popover must fit mobile viewport');
  await page.keyboard.press('Escape');
  await page.locator('#festival-pwa-menu').waitFor({state:'hidden'});
  await page.setViewportSize({width:1440,height:900});
  await page.locator('.festival-brand-icon').hover();
  await page.locator('#festival-pwa-menu').waitFor({state:'visible'});
  await page.locator('.festival-brand-icon').click();
  await page.locator('#festival-pwa-menu').waitFor({state:'visible'});
  await page.keyboard.press('Escape');
  await page.locator('#festival-pwa-menu').waitFor({state:'hidden'});
  await page.setViewportSize({width:390,height:844});
  await page.setViewportSize({width:1440,height:900});
  await page.locator('.festival-brand-icon').hover();
  await page.locator('#festival-pwa-menu').waitFor({state:'visible'});
  await page.locator('.festival-brand-icon').click();
  await page.locator('#festival-pwa-menu').waitFor({state:'visible'});
  await page.keyboard.press('Escape');
  await page.locator('#festival-pwa-menu').waitFor({state:'hidden'});
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>{window.__navigationTest='persisted';});
  await page.locator('.app-nav a[href="/songs/"]').click();
  await page.waitForURL('**/songs/');
  await page.locator('#catalog-search').waitFor();
  assert.equal(await page.evaluate(()=>window.__navigationTest),'persisted','SPA navigation must keep the same window');
  await page.waitForFunction(()=>performance.getEntriesByName('masljanica-nav-swap').length>0);
  console.log('Navigation timing (first SPA swap):',await page.evaluate(()=>Math.round(performance.getEntriesByName('masljanica-nav-swap').at(-1).duration)),'ms');
  const search=page.locator('#catalog-search');
  await search.fill('несуществующаяпесня');
  await page.locator('#catalog-empty').waitFor({state:'visible'});
  await search.fill('');
  await page.locator('#catalog-empty').waitFor({state:'hidden'});
  assert.equal(await page.locator('.song-row').count(),15);
  const row=page.locator('.song-row').filter({hasText:'Квашня'});
  await row.locator('summary').click();
  await row.locator('.song-lyrics').waitFor({state:'visible'});
  assert.equal(await row.locator('.song-variant').count(),2);
  assert.equal(await row.locator('iframe').count(),0,'Video is lazy loaded');
  await row.locator('.song-video-load').click();
  await row.locator('iframe').waitFor({state:'visible'});
  await page.waitForFunction(()=>document.querySelector('[data-song="Квашня"] iframe')?.getAttribute('src')?.includes('youtube-nocookie'));
  await context.setOffline(true);
  await row.locator('.song-video').waitFor({state:'hidden'});
  assert.equal(await row.locator('iframe').count(),0,'Hot offline hides and releases external video');
  await row.locator('.song-lyrics').waitFor({state:'visible'});
  await row.locator('.song-variant').first().waitFor({state:'visible'});
  await context.setOffline(false);
  await row.locator('.song-video-load').waitFor({state:'visible'});
  assert.equal(await row.locator('iframe').count(),0,'Manual video waits for a click on reconnect');
  const second=row.locator('.song-variant').nth(1);
  const selected=await second.getAttribute('data-src');
  assert.match(selected,/^\/media\/audio\//);
  await second.click();
  await page.waitForFunction(()=>document.querySelector('[data-song="Квашня"] .song-variant[data-variant="1"]')?.dataset.playing==='true');
  assert.equal(await second.getAttribute('data-selected'),'true');
  assert.equal(await row.locator('.song-variant').first().getAttribute('data-selected'),'false');
  await page.waitForFunction(()=>{const r=document.querySelector('[data-song="Квашня"]');const a=r?.querySelector('[data-variant="0"]'),b=r?.querySelector('[data-variant="1"]');return a&&b&&b.getBoundingClientRect().width>a.getBoundingClientRect().width+20;});
  await row.locator('summary').click();
  await row.locator('.song-lyrics').waitFor({state:'hidden'});
  assert.equal(await row.locator('details').getAttribute('open'),null,'Closing lyrics must not stop playback');
  const transport=page.locator('#song-player-audio');
  assert.equal(await transport.getAttribute('src'),selected);
  await page.waitForFunction(()=>{const a=document.querySelector('#song-player-audio');return a&&!a.paused&&a.currentTime>0.25&&a.readyState>=2;},{},{timeout:20000});
  await page.waitForFunction(()=>Number(document.querySelector('[data-song="Квашня"] .song-play')?.style.getPropertyValue('--song-progress'))>0);
  // The actual transport must advance the playlist when a recording finishes.
  await transport.evaluate(a=>{a.currentTime=Math.max(0,a.duration-0.15);});
  await page.waitForFunction(src=>{const a=document.querySelector('#song-player-audio');return a&&a.getAttribute('src')!==src&&a.currentTime>0.1&&!a.paused;},selected,{timeout:20000});
  await row.locator('.song-play').click();
  await page.waitForFunction(()=>document.querySelector('[data-song="Квашня"] .song-play')?.dataset.playing==='true');
  await row.locator('.song-play').click();
  await page.waitForFunction(()=>document.querySelector('[data-song="Квашня"] .song-play')?.dataset.playing==='false');
  assert.equal(new URL(page.url()).pathname,'/songs/');
  await page.locator('.app-nav a[href="/games/"]').click();
  await page.waitForURL('**/games/');
  await page.locator('#catalog-search').fill('несуществующаяигра');
  await page.locator('#catalog-empty').waitFor({state:'visible'});
  await page.locator('.more-menu summary').click();
  await page.locator('.more-links a[href="/offline/"]').click();
  await page.waitForURL('**/offline/');
  await page.locator('#offline-update:not([disabled])').waitFor();
  await page.locator('#offline-update').click();
  await page.waitForFunction(()=>document.documentElement.dataset.offlineReady==='true',{},{timeout:180000});
  const audio=await page.evaluate(async()=>{
    const data=await (await fetch('/offline-manifest.json')).json();
    return data.entries.find(e=>e.url.endsWith('.mp3'))?.url;
  });
  assert.ok(audio,'Local audio must be present in the offline pack');
  await context.setOffline(true);
  await page.reload();
  await page.locator('#offline-status').waitFor();
  await page.waitForFunction(()=>document.documentElement.dataset.offlineReady==='true');
  await page.locator('.app-nav a[href="/songs/"]').click();
  await page.waitForURL('**/songs/');
  await page.locator('[data-entry]').first().waitFor();
  const coldRow=page.locator('.song-row').filter({hasText:'Квашня'});
  await coldRow.locator('summary').click();
  await coldRow.locator('.song-lyrics').waitFor({state:'visible'});
  await coldRow.locator('.song-video').waitFor({state:'hidden'});
  assert.equal(await coldRow.locator('iframe').count(),0,'Cold offline never creates a video iframe');
  await coldRow.locator('summary').click();
  await coldRow.locator('.song-play').click();
  await page.waitForFunction(()=>{const a=document.querySelector('#song-player-audio');return a&&!a.paused&&a.currentTime>0.25&&a.readyState>=2&&a.getAttribute('src').startsWith('/media/audio/');},{},{timeout:20000});
  await coldRow.locator('.song-play').click();
  const offlineRequests=providerRequests;
  await page.goto(origin+'/games/'+encodeURIComponent('дударь')+'/');
  await page.locator('[data-external-embed]').waitFor({state:'attached'});
  await page.locator('[data-external-embed]').waitFor({state:'hidden'});
  assert.equal(await page.locator('[data-external-embed] iframe').count(),0,'Cold offline game page must not create a provider iframe');
  assert.equal(providerRequests,offlineRequests,'No provider requests during cold offline');
  await context.setOffline(false);
  await page.locator('[data-external-embed] iframe').waitFor({state:'visible'});
  await context.setOffline(true);
  await page.locator('[data-external-embed]').waitFor({state:'hidden'});
  assert.equal(await page.locator('[data-external-embed] iframe').count(),0,'Hot offline game page releases the provider');
  const range=await page.evaluate(async url=>{
    const response=await fetch(url,{headers:{Range:'bytes=0-127'}});
    return {status:response.status,bytes:(await response.arrayBuffer()).byteLength,range:response.headers.get('content-range')};
  },audio);
  assert.equal(range.status,206);assert.equal(range.bytes,128);assert.match(range.range,/^bytes 0-127\//);
  await context.close();
  console.log('SPA, search and complete offline audio smoke test passed.');
} finally {
  await browser?.close();
  server.kill();
}
